type Ctx = {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string) => string
}

const I18nCtx = createContext<Ctx | null>(null)

function getInitialLang(): Lang {
  try {
    const saved = localStorage.getItem('openapi_lang') as Lang | null
    if (saved === 'zh' || saved === 'en') return saved
    return 'en'
  } catch {
    return 'en'
  }
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangRaw] = useState<Lang>(() => getInitialLang())
  useEffect(() => {
    try {
      localStorage.setItem('openapi_lang', lang)
    } catch {
      /* ignore */
    }
    document.documentElement.lang = lang
  }, [lang])
  const setLang = useCallback((l: Lang) => setLangRaw(l), [])
  const t = useCallback((key: string) => dict[lang][key] ?? dict.en[key] ?? key, [lang])
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t])
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nCtx)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}
